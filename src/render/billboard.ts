// Creature face drawing. Three modes (spec section 7):
//   A dithered billboard quad in the world, with a wireframe cage
//   B contour line paths drawn like wall segments
//   C portrait panel in the HUD (drawn by hud.ts; this module supplies
//     the image)
// When faces.json holds no entry, a procedural wireframe head built
// from the creature's silhouette key stands in.

import { tuning } from '../config/tuning.ts';
import type { Content, GameState } from '../sim/step.ts';
import type { CreatureInstance } from '../sim/creatures.ts';
import { type Camera, toCameraSpace, projectCameraSpace, scaleAt } from './camera.ts';
import type { SceneInsert } from './wireframe.ts';
import facesRaw from '../data/faces.json';

export type FaceMode = 'A' | 'B' | 'C';

interface FaceEntry {
  img96?: string;
  img48?: string;
  contours?: number[][];
  credit?: string;
}

const faces = facesRaw as Record<string, FaceEntry>;

// Face images generated by the build script, bundled by Vite when present.
const faceUrls: Record<string, string> = {};
const globbed = import.meta.glob('../assets/faces/*.png', { eager: true, query: '?url', import: 'default' });
for (const [path, url] of Object.entries(globbed)) {
  const name = path.split('/').pop()!.replace('.png', '');
  faceUrls[name] = url as string;
}

export function faceCredits(): { creatureId: string; credit: string }[] {
  return Object.entries(faces)
    .filter(([, entry]) => entry.credit)
    .map(([creatureId, entry]) => ({ creatureId, credit: entry.credit! }));
}

