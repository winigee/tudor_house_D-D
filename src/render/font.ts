export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;
export const LINE_HEIGHT = 9;

/** Draw a text run at (x, y) top-left in the current fill colour. */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number): void {
  let cx = x;
  for (const raw of text.toUpperCase()) {
    const rows = GLYPHS[raw] ?? GLYPHS['?']!;
    for (let r = 0; r < GLYPH_H; r++) {
      const bits = rows[r]!;
      for (let b = 0; b < GLYPH_W; b++) {
        if (bits & (1 << (GLYPH_W - 1 - b))) ctx.fillRect(cx + b, y + r, 1, 1);
      }
    }
    cx += ADVANCE;
  }
}

export function textWidth(text: string): number {
  return text.length * ADVANCE;
}
